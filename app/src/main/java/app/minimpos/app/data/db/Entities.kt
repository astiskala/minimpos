/**
 * A tax rate products can use (table `tax_rates`), managed in Settings › Tax.
 *
 * At least one rate always exists: the starter rates of the device's country (always including a 0% rate) are seeded
 * on first launch, and the last one cannot be deleted. A rate cannot be deleted either while products use it (the
 * products' foreign key is `RESTRICT`). Sales copy the name and rate onto their lines, so editing a rate never changes
 * past receipts.
 *
 * @property id Row ID generated by Room; 0 for a rate that has not been inserted yet.
 * @property name Label printed on receipts and in the tax breakdown, such as "GST 10%" or "No tax".
 * @property rateMilliPercent The rate in thousandths of a percent: 10% is 10_000 and 0 marks a zero rate.
 * @property sortOrder Position in lists (ascending); ties are ordered by highest rate first, then by name.
 */
@Entity(tableName = "tax_rates")
data class TaxRateEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val rateMilliPercent: Int,
    val sortOrder: Int = 0,
)

/**
 * A product category (table `categories`) used to group the tiles on the sale screen.
