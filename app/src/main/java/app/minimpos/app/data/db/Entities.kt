/** What a payment is, and so which products it sells; stored by name in `products.kind` and `sales.kind`. */
enum class SaleKind {
    /** A normal sale: any number of sale products and custom items, charged (and captured) straight away. */
    SALE,

    /**
     * A pre-authorisation: one pre-authorisation product or custom amount, only held on the card. It is captured (or
     * what it holds adjusted) through Adyen's Checkout API, or cancelled from history; it can be refunded only once
     * captured, up to the amount captured.
     */
    PRE_AUTHORISATION,
    ;

    /**
     * Whether a payment of this kind holds a single item with a quantity of one, so adding a product or custom item
     * replaces the cart: a pre-authorisation.
     */
    val singleItem: Boolean get() = this == PRE_AUTHORISATION
}

/**
